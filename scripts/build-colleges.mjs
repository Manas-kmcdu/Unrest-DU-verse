#!/usr/bin/env node
/* Build the college pages.

   node scripts/build-colleges.mjs          pages + assets/colleges-data.js (+ sitemap.xml when SITE_URL is set). No dependencies.
   node scripts/build-colleges.mjs --og     also render assets/og/<slug>.png (1200x630). Needs Playwright with Chromium.

   Reads:   data/colleges.ts (the only place colleges live), assets/config.js (SITE_URL), index.html (header, footer, icons, fonts)
   Writes:  assets/colleges-data.js, colleges/<slug>/index.html, assets/og/<slug>.png, sitemap.xml
   SITE_URL can also come from the environment:  SITE_URL=https://unrest.in node scripts/build-colleges.mjs --og */
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import vm from "node:vm";
import { createRequire } from "node:module";
import { execSync } from "node:child_process";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const req = createRequire(import.meta.url);
const read = (p) => fs.readFileSync(path.join(ROOT, p), "utf8");
const write = (p, s) => { const f = path.join(ROOT, p); fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, s); };
const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const MARK = "<!-- generated by scripts/build-colleges.mjs: edit data/colleges.ts and re-run, not this file -->";
const WANT_OG = process.argv.includes("--og");

/* ---------- data ---------- */
const ts = read("data/colleges.ts");
const arr = ts.match(/export const COLLEGES: College\[\] = (\[[\s\S]*?\n\]);/);
if (!arr) throw new Error("data/colleges.ts: could not find `export const COLLEGES: College[] = [ ... ];`");
const colleges = vm.runInNewContext("(" + arr[1] + ")");
const seen = new Set();
for (const c of colleges) {
  const where = `data/colleges.ts (${c.slug || "?"})`;
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(c.slug || "")) throw new Error(where + ": slug must be lowercase letters, digits and hyphens");
  if (seen.has(c.slug)) throw new Error(where + ": duplicate slug");
  seen.add(c.slug);
  if (!c.name || !c.shortName) throw new Error(where + ": name and shortName are required");
  if (c.campus !== "North" && c.campus !== "South") throw new Error(where + ": campus must be North or South");
  if (!/^#[0-9a-f]{6}$/i.test(c.accentColour || "")) throw new Error(where + ": accentColour must be a #RRGGBB hex");
  if (!Number.isInteger(c.userCount) || c.userCount < 0) throw new Error(where + ": userCount must be a whole number >= 0");
  if (!c.buildingIllustration) throw new Error(where + ": buildingIllustration is required");
}

/* ---------- config ---------- */
const sandbox = {}; vm.runInNewContext(read("assets/config.js"), { window: sandbox });
const SITE = String(process.env.SITE_URL || (sandbox.UNREST_CONFIG || {}).SITE_URL || "").replace(/\/+$/, "");
if (!SITE) console.warn("! SITE_URL is empty: og:image and canonical use relative paths. Social crawlers need absolute URLs, so set SITE_URL in assets/config.js before launch and re-run.");

/* ---------- shared core (same file the browser uses) ---------- */
const core = req(path.join(ROOT, "assets/college-core.js"));
core.setColleges(colleges);

/* ---------- pieces borrowed from index.html so the pages never drift from it ---------- */
const idx = read("index.html");
const pick = (re, what) => { const m = idx.match(re); if (!m) throw new Error("index.html: could not find " + what); return m[0]; };
const header = pick(/<header class="d">[\s\S]*?<\/header>/, "<header class=\"d\">")
  .replace(/href="#top"/g, 'href="../../"').replace(/href="#/g, 'href="../../#').replace(/href="events\//g, 'href="../../events/');
const footer = pick(/<footer class="d">[\s\S]*?<\/footer>/, "<footer class=\"d\">").replace(/href="events\//g, 'href="../../events/');
const icons = pick(/<link rel="icon"[^>]*>/, "favicon link") + "\n" + pick(/<link rel="apple-touch-icon"[^>]*>/, "apple-touch-icon link");
const fonts = pick(/<link rel="preconnect"[^>]*>\s*<link href="https:\/\/fonts\.googleapis\.com[^>]*>/, "Google Fonts links");

/* ---------- per-college copy ---------- */
const abs = (p) => (SITE ? SITE + "/" + p : "../../" + p);
function seo(c) {
  const base = `${c.name} on Unrest`, long = base + " | Verified DU network";
  return {
    title: long.length <= 60 ? long : base,
    desc: `Join ${c.name} on Unrest, the verified network for Delhi University students. Find your people, see what's on at ${c.shortName} and make plans.`,
    url: SITE ? `${SITE}/colleges/${c.slug}/` : "",
    img: abs(`assets/og/${c.slug}.png`),
  };
}
const about = (c) => c.about || `${c.name} is on ${c.campus} Campus. On Unrest, its students find each other: people from your course, what your societies are planning, and the plans being made around ${c.shortName}. Join with your college and see who's already in.`;

/* ---------- page ---------- */
function page(c) {
  const s = seo(c), n = core.getCount(c), m = core.milestone(n);
  const others = colleges.filter((o) => o.campus === c.campus && o.slug !== c.slug);
  const sel = ["North", "South"].map((cp) => `<optgroup label="${cp} Campus">` + colleges.filter((o) => o.campus === cp)
    .map((o) => `<option value="${esc(o.slug)}"${o.slug === c.slug ? " selected" : ""}>${esc(o.name)}</option>`).join("") + "</optgroup>").join("");
  const years = '<option value="">Select year</option>' + Object.keys(core.YEARS).map((k) => `<option value="${k}">${esc(core.YEARS[k])}</option>`).join("");
  return `<!doctype html>
${MARK}
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>${esc(s.title)}</title>
<meta name="color-scheme" content="dark light">
<meta name="theme-color" content="#0B0B0C">
<meta name="description" content="${esc(s.desc)}">
${s.url ? `<link rel="canonical" href="${esc(s.url)}">\n` : ""}<meta property="og:type" content="website"><meta property="og:site_name" content="unrest">
<meta property="og:title" content="${esc(s.title)}">
<meta property="og:description" content="${esc(s.desc)}">
${s.url ? `<meta property="og:url" content="${esc(s.url)}">\n` : ""}<meta property="og:image" content="${esc(s.img)}"><meta property="og:image:width" content="1200"><meta property="og:image:height" content="630"><meta property="og:image:alt" content="${esc(c.name)} on Unrest">
<meta name="twitter:card" content="summary_large_image"><meta name="twitter:title" content="${esc(s.title)}"><meta name="twitter:description" content="${esc(s.desc)}"><meta name="twitter:image" content="${esc(s.img)}">
${icons}
<script src="../../assets/theme.js"></script>
${fonts}
<link rel="stylesheet" href="../../assets/site.css">
<link rel="stylesheet" href="../../assets/colleges.css">
</head>
<body data-slug="${esc(c.slug)}">
${header}

<main id="top">
<section class="cp d" style="--c:${esc(c.accentColour)}"><div class="wrap">
 <a class="bc" href="../../#colleges"><span aria-hidden="true">&larr;</span> All colleges</a>
 <div class="cp-grid"><div>
  <p class="eb">${c.campus} Campus &middot; Delhi University</p>
  <h1>${esc(c.name)}</h1>
  <p class="cp-count"><b id="cnt" aria-hidden="true">${n}</b><span class="sr" id="cntsr">${n}</span><span>students already on Unrest</span></p>
  <div class="cp-bar" id="bar" role="progressbar" aria-label="Progress to ${m.target} students" aria-valuemin="0" aria-valuemax="${m.target}" aria-valuenow="${n}"><i style="width:${m.pct}%"></i></div>
  <p class="cp-ms"><span id="rem">${m.remaining}</span> more to reach <span id="tgt">${m.target}</span>.</p>
  <p class="cp-about">${esc(about(c))}</p>
  <div class="cta"><button class="btn" type="button" data-join>Join Unrest from ${esc(c.shortName)}</button></div>
  <div class="cp-share"><span class="eb">Share</span><a class="btn s sm" id="sh-wa" href="#" target="_blank" rel="noopener">WhatsApp</a><button class="btn s sm" id="sh-ig" type="button">Instagram story</button></div>
 </div>
 <div class="cp-art"><div class="ar">${core.artHTML(c, "../../")}</div></div></div>
</div></section>

<section class="l"><div class="wrap pad"><div class="lbs"><div>
 <p class="eb">Leaderboard</p><h2>Top colleges on Unrest</h2>
 <p class="mu" style="margin-top:24px;max-width:26em">Every student you bring in moves ${esc(c.shortName)} up the board.</p></div>
 <div id="lb">${core.leaderboardHTML({ n: 5, base: "../", highlight: c.slug })}</div></div>
 ${others.length ? `<div class="mcw"><p class="eb">More on ${c.campus} Campus</p><ul class="mc">${others.map((o) => `<li><a href="../${esc(o.slug)}/">${esc(o.name)}</a></li>`).join("")}</ul></div>` : ""}
</div></section>

<section class="band"><div class="wrap"><h2 style="max-width:12em">Your campus is already talking.</h2><button class="btn inv" type="button" data-join>Join Unrest from ${esc(c.shortName)}</button></div></section>
</main>

${footer}

<dialog class="dlg" id="jd" aria-labelledby="jdt"><div class="dlg-in">
 <button class="dlg-x" type="button" data-close aria-label="Close"><svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" aria-hidden="true"><path d="M6 6l12 12M18 6L6 18"/></svg></button>
 <div id="jv-form">
  <p class="eb">Join from ${esc(c.shortName)}</p><h2 id="jdt">Get on Unrest.</h2>
  <form id="jf" novalidate>
   <div class="fld"><label for="f-name">Name</label><input class="fi" id="f-name" name="name" type="text" autocomplete="name" maxlength="80" aria-describedby="e-name" autofocus><p class="fe" id="e-name" aria-live="polite"></p></div>
   <div class="fld"><label for="f-college">College</label><select class="fi" id="f-college" name="college" aria-describedby="e-college">${sel}</select><p class="fe" id="e-college" aria-live="polite"></p></div>
   <div class="fld"><label for="f-year">Year</label><select class="fi" id="f-year" name="year" aria-describedby="e-year">${years}</select><p class="fe" id="e-year" aria-live="polite"></p></div>
   <div class="fld"><label for="f-contact">College email or phone</label><input class="fi" id="f-contact" name="contact" type="text" inputmode="email" autocapitalize="none" autocomplete="email" placeholder="Email or mobile number" aria-describedby="h-contact e-contact"><p class="fh" id="h-contact">Use your college email, or a mobile number.</p><p class="fe" id="e-contact" aria-live="polite"></p></div>
   <div class="hp" aria-hidden="true"><label>Website<input name="website" type="text" tabindex="-1" autocomplete="off"></label></div>
   <p id="jerr" role="alert" hidden></p>
   <button class="btn w" id="jsub" type="submit">Join Unrest</button>
  </form>
 </div>
 <div id="jv-ok" hidden>
  <h2 id="ok-h" tabindex="-1">Got it.</h2>
  <p class="mu" id="ok-p" style="margin-top:16px"></p>
  <div class="ok-share"><a class="btn" id="bring" href="#" target="_blank" rel="noopener">Bring your college in</a><button class="btn s" id="ok-ig" type="button">Copy for Instagram story</button></div>
  <p class="ok-demo" id="ok-demo" hidden>Demo mode: this signup was not sent anywhere. Set SIGNUP_ENDPOINT in assets/config.js.</p>
  <p style="margin-top:24px"><button class="btn s sm" type="button" data-close>Done</button></p>
 </div>
</div></dialog>
<div class="toast" id="toast" role="status" aria-live="polite"></div>

<script src="../../assets/config.js"></script>
<script src="../../assets/colleges-data.js"></script>
<script src="../../assets/college-core.js"></script>
<script src="../../assets/college-page.js"></script>
</body>
</html>
`;
}

/* ---------- write ---------- */
write("assets/colleges-data.js",
  "/* GENERATED by scripts/build-colleges.mjs from data/colleges.ts. Do not edit.\n   userCount values are PLACEHOLDER until COUNTS_ENDPOINT is set in assets/config.js. */\n" +
  "window.UNREST_COLLEGES=" + JSON.stringify(colleges) + ";\n");

const slugs = new Set(colleges.map((c) => c.slug));
for (const c of colleges) write(`colleges/${c.slug}/index.html`, page(c));

/* remove pages for colleges that were deleted from data/colleges.ts (only files this script made) */
const dir = path.join(ROOT, "colleges");
for (const d of fs.readdirSync(dir)) {
  const f = path.join(dir, d, "index.html");
  if (!slugs.has(d) && fs.existsSync(f) && fs.readFileSync(f, "utf8").includes(MARK)) { fs.rmSync(path.join(dir, d), { recursive: true }); console.log("- removed colleges/" + d); }
}

/* hand-written pages that live next to the generated ones and should be in the sitemap. Add new public pages here. */
const EXTRA_PAGES = ["/download.html", "/join-us.html", "/versus.html", "/privacy.html", "/terms.html", "/child-safety.html", "/delete-account.html"];
if (SITE) {
  const urls = [SITE + "/", SITE + "/events/", ...EXTRA_PAGES.map((p) => SITE + p), ...colleges.map((c) => `${SITE}/colleges/${c.slug}/`)];
  write("sitemap.xml", `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.map((u) => `  <url><loc>${esc(u)}</loc></url>`).join("\n")}\n</urlset>\n`);
}
console.log(`built ${colleges.length} college pages, assets/colleges-data.js${SITE ? ", sitemap.xml" : ""}`);

/* ---------- OG images (optional) ---------- */
async function og() {
  let pw;
  for (const get of [() => req("playwright"), () => req(path.join(execSync("npm root -g", { encoding: "utf8" }).trim(), "playwright"))]) { try { pw = get(); break; } catch {} }
  if (!pw) { console.warn("! --og needs Playwright (npm i -D playwright && npx playwright install chromium). Skipped."); return; }
  const browser = await pw.chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 1200, height: 630 }, deviceScaleFactor: 1 });
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "unrest-og-"));
  for (const c of colleges) {
    const custom = /[\/.]/.test(c.buildingIllustration);
    const art = custom
      ? `<img src="${esc(pathToFileURL(path.join(ROOT, c.buildingIllustration)).href)}" alt="">`
      : `<svg viewBox="0 0 200 110"><style>*{fill:none;stroke:${c.accentColour};stroke-width:1.4;stroke-linecap:round;stroke-linejoin:round}.f{fill:${c.accentColour};fill-opacity:.16}</style>${core.artInner(c)}</svg>`;
    const fs1 = c.name.length <= 18 ? 96 : c.name.length <= 28 ? 76 : 62;
    /* No numbers on purpose: counts are placeholders and an image can't be updated by the endpoint. */
    const html = `<!doctype html><meta charset="utf-8"><style>
*{box-sizing:border-box;margin:0}body{width:1200px;height:630px;position:relative;overflow:hidden;background:#0B0B0C;color:#FAFAF8;font-family:"Inter Tight",Inter,sans-serif}
.tint{position:absolute;inset:0;background:${c.accentColour};opacity:.07}
.logo{position:absolute;left:72px;top:60px;font:400 64px/1 "Times New Roman MT Condensed","Times New Roman","Liberation Serif",Times,serif;letter-spacing:-.02em;transform:scaleX(.8);transform-origin:0 50%}.logo i{font-style:italic}
.art{position:absolute;right:56px;bottom:56px;width:560px}.art svg,.art img{display:block;width:100%}
.t{position:absolute;left:72px;bottom:64px;max-width:600px}
.eb{font:500 20px Inter,sans-serif;text-transform:uppercase;letter-spacing:.16em;color:#A1A1A0;margin-bottom:20px}
h1{font-weight:600;font-size:${fs1}px;line-height:.98;letter-spacing:-.045em}
.s{margin-top:24px;font:400 28px Inter,sans-serif;color:#A1A1A0}
</style><div class="tint"></div><div class="logo">Un<i>rest</i></div><div class="art">${art}</div>
<div class="t"><p class="eb">${c.campus} Campus &middot; Delhi University</p><h1>${esc(c.name)}</h1><p class="s">Find your people on Unrest.</p></div>`;
    const f = path.join(tmp, c.slug + ".html"); fs.writeFileSync(f, html);
    const p = await ctx.newPage(); await p.goto(pathToFileURL(f).href); await p.evaluate(() => document.fonts.ready);
    fs.mkdirSync(path.join(ROOT, "assets/og"), { recursive: true });
    await p.screenshot({ path: path.join(ROOT, "assets/og", c.slug + ".png") }); await p.close();
  }
  await browser.close(); fs.rmSync(tmp, { recursive: true, force: true });
  console.log(`rendered ${colleges.length} OG images in assets/og/`);
}
if (WANT_OG) await og();
else if (!fs.existsSync(path.join(ROOT, "assets/og"))) console.warn("! assets/og/ is missing: run with --og so each page's og:image exists.");
